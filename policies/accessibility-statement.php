    <h1>Accessibility Statement</h1>
    <p><strong>Effective date:</strong> September 22, 2026</p>
    
<h2>Our commitment</h2>
<p>This catalog is built for shoppers aged 60 and over, and accessibility is not an add-on to that &mdash; it is the brief. We aim to meet <strong>WCAG 2.1 Level AA</strong> across this site, and we exceed it in several places because our customers benefit.</p>

<h2>What we have built in</h2>
<ul>
  <li><strong>Large type.</strong> Body text is 19&ndash;20 pixels. Nothing on this site, including footers and legal pages, is set below 16 pixels.</li>
  <li><strong>High contrast.</strong> Body text meets WCAG AAA contrast (7:1 or better) against its background. Button text exceeds the AA requirement.</li>
  <li><strong>Underlined links.</strong> Every link is underlined, so it is identifiable without relying on color.</li>
  <li><strong>Large targets.</strong> Buttons and menu items are at least 48 pixels tall with generous padding.</li>
  <li><strong>Keyboard access.</strong> Every part of the site, including the whole checkout form, can be operated with the Tab and Enter keys. A thick, high-contrast focus ring shows where you are.</li>
  <li><strong>Text labels.</strong> No icon appears without a text label beside it.</li>
  <li><strong>Alternative text.</strong> Every meaningful image has a description for screen readers.</li>
  <li><strong>Nothing moves.</strong> There are no carousels, auto-playing videos, countdown timers, pop-ups, or animations anywhere on this site. We also honor the reduced-motion setting in your operating system.</li>
  <li><strong>Reflow, not shrink.</strong> On a small screen or at 200% zoom, the text stays full size and the layout reflows into a single column. There is no horizontal scrolling.</li>
  <li><strong>Print styles.</strong> Product pages, the How to Order page, and the mail-in order form print cleanly in black on white with web addresses spelled out.</li>
  <li><strong>Plain language.</strong> We write &ldquo;Free returns for 30 days,&rdquo; not &ldquo;hassle-free RMA process.&rdquo;</li>
</ul>

<h2>Known limitations</h2>
<ul>
  <li>Some product photographs come from photographic archives and vary in lighting and background. We describe each one in its alternative text.</li>
  <li>Typefaces load from Google Fonts. If that service is blocked or slow, the page falls back to Georgia and Arial; sizes and contrast are unaffected.</li>
  <li>When our hosted payment page goes live, that page is operated by our payment provider and is outside our direct control. We have chosen a provider that publishes its own accessibility conformance report, and we will test the flow ourselves before switching it on.</li>
</ul>

