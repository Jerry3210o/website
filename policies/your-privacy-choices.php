<h2>Do Not Sell or Share My Personal Information</h2>
<p>We do not sell your personal information for money and never have. We may &ldquo;share&rdquo; identifiers with Google for advertising purposes, which California law treats as sharing for cross-context behavioral advertising. You can stop that at any time, and here is how.</p>

<h2>Three ways to opt out</h2>
<ul>
  <li><strong>Turn on Global Privacy Control.</strong> If your browser or a browser extension sends the GPC signal, we honor it automatically as an opt-out for that browser. You do not need to contact us, and we will not ask you to confirm anything.</li>
  <li><strong>Telephone.</strong> Call <a href="tel:+15555550147">(555) 010-0147</a>, Mon&ndash;Fri 9 AM&ndash;6 PM ET, and say you want to opt out of the sale and sharing of your personal information. That is the whole conversation; we will not try to talk you out of it.</li>
  <li><strong>Email.</strong> Write to <a href="mailto:orders@porchlightgeneral.example">orders@porchlightgeneral.example</a> with the words &ldquo;opt out&rdquo; in the subject line.</li>
</ul>
<p>You do not need an account to opt out. You do not need to be a customer. You do not need to give a reason.</p>

<h2>What happens next</h2>
<p>We act on a GPC signal immediately for that browser. For a telephone or email request, we process it within 15 business days and confirm to you in writing when it is done. In the meantime we stop any further sharing straight away.</p>
<p>Opting out does not close your account, cancel an order, or change any price. It does not stop us emailing you about an order you placed.</p>

<h2>Authorized agents</h2>
<p>You may use an authorized agent to make this request on your behalf. Send us written permission signed by you, and we may contact you directly to confirm that you authorized it. If the agent holds power of attorney, the power of attorney alone is enough.</p>

<h2>Your other choices</h2>
<ul>
  <li><strong>Opt out of personalized Google ads:</strong> <a href="https://adssettings.google.com">adssettings.google.com</a></li>
  <li><strong>Opt out of Google Analytics:</strong> <a href="https://tools.google.com/dlpage/gaoptout">tools.google.com/dlpage/gaoptout</a></li>
  <li><strong>Block or delete cookies</strong> in your browser settings &mdash; see our <a href="cookie-policy.php">Cookie Policy</a>.</li>
  <li><strong>Ask us to delete everything</strong> we hold about you &mdash; see the <a href="privacy-policy.php">Privacy Policy</a>.</li>
</ul>

