    <h1>Return &amp; Refund Policy</h1>
    <p><strong>Effective date:</strong> September 22, 2026</p>
    
<h2>The short version</h2>
<p>You have 30 days from the day your parcel is delivered to return almost anything for a full refund. We pay the return shipping. There is no restocking fee &mdash; not a reduced one, none at all.</p>

<h2>Return window</h2>
<p>Thirty calendar days, counted from the delivery date shown by the carrier. If the thirtieth day falls on a Sunday or a federal holiday, the next business day counts.</p>

<h2>Condition of the item</h2>
<p>Items should come back in the condition you received them, with any tags, manuals, and parts. You are welcome to have taken the item out of the box and looked at it &mdash; that is what a 30-day return is for. An item that has been used to the point that we cannot resell it may be refunded in part; we will call you before we do that, and you can have the item sent back to you instead.</p>

<h2>How to start a return</h2>
<ul>
  <li><strong>By telephone:</strong> call <a href="tel:+15555550147">(555) 010-0147</a>, Mon&ndash;Fri 9 AM&ndash;6 PM ET. This is the fastest way.</li>
  <li><strong>By email:</strong> write to <a href="mailto:orders@porchlightgeneral.example">orders@porchlightgeneral.example</a> with your name, the item number, and what you would like to do.</li>
  <li><strong>By mail:</strong> write to Porchlight General LLC, 118 Depot Street, Suite 4, Springfield, IL 62701.</li>
</ul>
<p>You do not need an account, a login, or a code from an email to start a return. We will email or mail you a prepaid return label.</p>

<h2>Who pays return shipping</h2>
<p>We do. Every return label we issue is prepaid. If you would rather use your own carrier, you may, but we can only refund the item price in that case.</p>

<h2>Restocking fee</h2>
<p>There is none. We do not charge a restocking fee on any item in this catalog.</p>

<h2>Items that cannot be returned</h2>
<p>Only these, and only once the package has been opened, because they are food-contact goods that cannot be inspected and resold:</p>
<ul><li>Porchlight Unbleached Cheesecloth, 9 Square Feet (Item No. PG-1018)</li></ul>
<p>If one of these arrives damaged, or is not what you ordered, call us and we will replace it or refund it in full. The exclusion is about resale, not about holding you to a mistake of ours.</p>

<h2>Damaged, defective, or wrong items</h2>
<p>Call or email us within 30 days of delivery. Tell us the item number and what is wrong; a photograph helps but is not required. We will send a replacement or a full refund, whichever you prefer, and we will arrange collection of the damaged item at our expense. We aim to have a replacement in the post within 2 business days of your call.</p>

<h2>Refunds</h2>
<p>Refunds go back to the original payment method &mdash; the same card, the same PayPal account, or a check if you paid by check. We do not refund in store credit unless you ask for it.</p>
<p>We issue the refund within 3 business days of your return reaching us. Your bank or card issuer then takes its own time to post it, usually 3 to 10 business days. A refund by check is mailed within 5 business days.</p>

<h2>Exchanges</h2>
<p>Tell us what you would like instead and we will send it as soon as your return is on its way back to us, rather than making you wait for the refund to clear first. If the new item costs more, we will call you for the difference; if it costs less, we refund the difference.</p>

<h2>Cancelling an order before it ships</h2>
<p>Call us. If the parcel has not left the building, we cancel it and refund you in full the same day. If it has already gone, refuse the delivery or send it back with the prepaid label and we refund in full.</p>

