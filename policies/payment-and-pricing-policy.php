    <h1>Payment &amp; Pricing Policy</h1>
    <p><strong>Effective date:</strong> September 22, 2026</p>
    
<h2>What the listed price includes</h2>
<p>The price shown on a product page is the full price of that item. It includes every mandatory fee we charge. There is no handling fee, no service fee, no processing fee, and no surcharge added later in the checkout.</p>
<p>The only things added at checkout are the shipping cost for the method you choose and the sales tax required by your delivery state &mdash; both shown to you before you commit. This is the requirement of California's Honest Pricing Law (SB 478, Civil Code &sect;1770(a)(29)), and we apply it to every order regardless of state.</p>

<h2>How to pay</h2>
<ul>
  <li><strong>By telephone:</strong> call <a href="tel:+15555550147">(555) 010-0147</a>, Mon&ndash;Fri 9 AM&ndash;6 PM ET, and we will take your card details over the telephone with you.</li>
  <li><strong>By mail:</strong> send a check or money order payable to Porchlight General LLC with the printable form on our <a href="../pages/how-to-order.php">How to Order</a> page. Please do not mail cash. Allow 7&ndash;10 business days for a check to clear.</li>
  <li><strong>Online:</strong> when online payment is switched on, you will pay by credit or debit card on our payment provider's secure page, or through PayPal. We will never ask for your card number on our own pages.</li>
</ul>
<p>We will never ask for your card number, PIN, or online banking password by email or text message. If you receive a message like that claiming to be from us, it is not from us &mdash; call the number at the top of this page.</p>

<h2>Sales tax</h2>
<p>Sales tax is calculated at checkout based on your delivery state, and on local rates within that state where they apply. Some states tax shipping charges and some do not; the checkout applies the rule for your address. Tax-exempt organizations should call us before ordering so we can record your exemption certificate.</p>

<h2>Price changes</h2>
<p>Prices may change as our costs change. The price that applies to your order is the one shown when you place it. If a price changes after you order but before we ship, you pay the price you agreed.</p>

<h2>No fictitious former prices</h2>
<p>You will not find a crossed-out &ldquo;was&rdquo; price anywhere in this catalog. FTC guidance (16 CFR &sect;233.1) permits a former price to be advertised only where the item was genuinely offered at that price for a reasonable period. This store is new, so no item here has such a history &mdash; and inventing one to make a discount look bigger is exactly the practice that rule exists to stop.</p>

<h2>Bundles and offers</h2>
<p>Where we list a bundle, the price is simply the sum of the items' everyday prices, ordered together; we say so plainly on the <a href="../pages/deals.php">Deals</a> page. Free shipping over $75 is an everyday term of business, not a limited-time offer. We do not run coupon codes at present. If that changes, the terms and the expiry date will be printed in full on the offer.</p>

<h2>Charges and refunds</h2>
<p>When online payment is switched on, your card will be charged when we dispatch your order, not when you place it. Refunds are returned to the original payment method as set out in our <a href="return-and-refund-policy.php">Return &amp; Refund Policy</a>.</p>

    <p>Questions about this policy? Call <a href="tel:+15555550147">(555) 010-0147</a>, Mon&ndash;Fri 9 AM&ndash;6 PM ET, email <a href="mailto:orders@porchlightgeneral.example">orders@porchlightgeneral.example</a>, or write to Porchlight General LLC, 118 Depot Street, Suite 4, Springfield, IL 62701.</p>
