    <h1>Warranty &amp; Product Safety</h1>
    <p><strong>Effective date:</strong> September 22, 2026</p>
    
<h2>Limited warranty</h2>
<p>We warrant every item in this catalog to be free of defects in materials and workmanship for <strong>one year from the date of delivery</strong>. If an item fails in normal household use within that year, we will repair it, replace it, or refund it &mdash; our choice, though we will listen to your preference.</p>
<p>The warranty does not cover normal wear, damage from misuse or accident, rust on cast iron that was stored wet, wood that split from being soaked or left in the sun, or any item modified after purchase.</p>

<h2>How to claim</h2>
<p>Call <a href="tel:+15555550147">(555) 010-0147</a>, Mon&ndash;Fri 9 AM&ndash;6 PM ET, or email <a href="mailto:orders@porchlightgeneral.example">orders@porchlightgeneral.example</a> with the item number and a description of the fault. Photographs help. You do not need the original packaging or a receipt if you ordered from us &mdash; we can look your order up by name and ZIP code.</p>

<h2>Safety notices by category</h2>
<h3>Cast iron and cookware</h3>
<p>Cast iron handles reach the temperature of the pan. Always use dry oven mitts or a folded towel, lift heavy pans with both hands, and set hot cookware on a trivet. A damp mitt conducts heat almost instantly &mdash; never use one.</p>

<h3>Glass and ceramics</h3>
<p>Glass and stoneware dislike sudden temperature change. Do not move a dish from the refrigerator into a hot oven, do not put a hot dish on a wet surface, and do not pour boiling liquid into cold glass. Inspect for chips before every use; discard any chipped piece that will hold food.</p>

<h3>Canning and fermentation</h3>
<p>Use only tested, current recipes from a reliable source for processing times and methods. Low-acid foods &mdash; vegetables, meat, poultry &mdash; require a pressure canner and cannot be safely processed in a water bath at any length of time. Never use a jar with a chipped rim, and never reuse a flat sealing lid. Discard any preserved food that smells wrong, shows mold, or comes from a jar whose seal has failed.</p>

<h3>Electrical items</h3>
<p>Our radio and record player plug into standard 120-volt household outlets. Keep cords out of walkways, do not run them under rugs, do not use them in bathrooms or near sinks, and unplug the unit before changing a stylus or cleaning it. Stop using any item whose cord or plug is damaged and call us.</p>

<h3>Batteries</h3>
<p>Several items take AA batteries. Keep loose batteries away from children and pets; swallowing a battery is a medical emergency &mdash; call 911 or the National Battery Ingestion Hotline at 800-498-8666 immediately. Remove batteries from anything being stored for months.</p>

<h3>Furniture and weight capacities</h3>
<p>The Slat-Back Porch Rocking Chair (PG-1032) is rated to <strong>250 lb</strong> and must be used on a level surface, clear of steps and walls. The Painted Wood Storage Chest (PG-1039) is rated to <strong>250 lb</strong> when sat on. Do not stand on either item. Check fasteners yearly and tighten anything loose.</p>

<h3>Rugs and mats</h3>
<p>Small rugs slide on smooth floors, which is a genuine fall risk. Always use a nonslip pad under a rug on tile, vinyl, or sealed wood, and replace any mat whose corners have begun to curl.</p>

<h3>Daily-living and comfort items</h3>
<p>Nothing in this catalog is a medical device, and nothing here treats, cures, prevents, or relieves any condition. If you are choosing household items because of a mobility, balance, or grip difficulty, please consult your physician or an occupational therapist about what will suit you &mdash; that advice is worth more than anything a catalog can tell you.</p>

<h2>Recall monitoring</h2>
<p>We check the Consumer Product Safety Commission's recall notices regularly. If an item we sold is recalled, we will contact every customer we shipped it to, using the details from the order, and tell you exactly what to do. You can also search recalls yourself at <a href="https://www.cpsc.gov/Recalls">cpsc.gov/Recalls</a>.</p>

<h2 id="prop65">California Proposition 65</h2>
<p>California's Proposition 65 (27 CCR &sect;25602) requires a warning before purchase for products that can expose a person to listed chemicals. Where a warning is required, it appears on the product page itself, above the point where you would buy, in this form:</p>
<p class="warning-line"><b>WARNING:</b> This product can expose you to chemicals which are known to the State of California to cause cancer or reproductive harm. For more information go to <a href="https://www.P65Warnings.ca.gov">www.P65Warnings.ca.gov</a>.</p>
<p>We record a Proposition 65 status for every item in our catalog as <em>required</em>, <em>not required</em>, or <em>confirm with supplier</em>. Items marked &ldquo;confirm with supplier&rdquo; are those where the finish, glaze, or plating composition must be verified before we can state a status with confidence &mdash; mainly enamelware, glazed stoneware, brass, and painted metal. If you would like the current documentation for a specific item before ordering, call us and we will get it for you.</p>

