    <h1>Shipping Policy</h1>
    <p><strong>Effective date:</strong> September 22, 2026</p>
    
<h2>Where we ship</h2>
<p>We ship to all 50 states, the District of Columbia, and APO, FPO, and DPO military addresses. We do not ship outside the United States, and we do not ship to freight forwarders.</p>
<p>Alaska, Hawaii, and military addresses ship by a slower service. Expect 10&ndash;21 business days rather than 3&ndash;7. Very heavy items &mdash; the rocking chair and the storage chest &mdash; may cost more to send to Alaska and Hawaii; we will call you with the exact cost before shipping and you may cancel at that point for a full refund.</p>

<h2>Processing time</h2>
<p>Orders placed before 2 PM Eastern on a business day are picked and packed the same day or the next. Orders placed on a weekend or a federal holiday are processed on the next business day. Our processing time is <strong>1&ndash;2 business days</strong>.</p>

<h2>Delivery estimates</h2>
