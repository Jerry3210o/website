<p>Transit times are the carrier's estimates and do not include our 1&ndash;2 day processing time. Weather and holidays can add days; the week after Thanksgiving is always the slowest of the year.</p>

<h2>Free shipping threshold</h2>
<p>Orders whose items total more than $75 before tax ship free by standard delivery. This is our everyday pricing, not a limited offer.</p>

<h2>Carriers and tracking</h2>
<p>We ship by the major national carriers and the United States Postal Service, choosing by destination and parcel size. When your parcel leaves us we email you a tracking number. If you would rather be told by telephone, say so when you order and we will call you instead.</p>

<h2>If we cannot ship on time</h2>
<p>Federal law (the FTC Mail, Internet, or Telephone Order Merchandise Rule, 16 CFR Part 435) requires us to ship within the time we state, or within 30 days if we state no time. If we cannot:</p>
<ul>
  <li>We will contact you before the deadline, by telephone or email, and tell you the new expected date.</li>
  <li>You may accept the delay or cancel the order. The choice is yours, and we will never treat silence as consent to a delay of more than 30 days.</li>
  <li>If you cancel, we refund the full amount to your original payment method &mdash; not store credit, not a voucher &mdash; promptly, and in any case within 7 business days.</li>
</ul>

<h2>Lost or damaged parcels</h2>
<p>If tracking shows delivered and the parcel is not there, wait one business day (carriers sometimes scan early), check with neighbors, then call us. If it does not turn up, we send a replacement or refund you in full. We handle the carrier claim ourselves; that is not your job.</p>
<p>If a parcel arrives damaged, keep the box and packing material and call us. Photographs help. We replace or refund at your choice and arrange collection at our expense.</p>

<h2>Address errors</h2>
<p>Check your address at checkout, especially the ZIP code. If you spot a mistake, call us straight away &mdash; if the parcel has not left, we will fix it at no cost. If it has already shipped to a wrong address you gave us, we will do what we can with the carrier, but we may have to charge the return shipping before sending it again.</p>

