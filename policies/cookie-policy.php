    <h1>Cookie Policy</h1>
    <p><strong>Effective date:</strong> September 22, 2026</p>
    
<h2>What a cookie is</h2>
<p>A cookie is a small text file that a website asks your browser to keep. It can be read back later by the website that set it, which is how a site remembers anything at all between pages.</p>

<h2>What this site uses</h2>
<p>Porchlight General is built as plain HTML and CSS with no JavaScript of its own, so the site itself sets no cookies. The categories below describe what is used when we run analytics or advertising, and what your choices are.</p>

<h3>1. Essential</h3>
<p>Cookies needed for the site to function &mdash; for example, a session cookie during checkout when online payment is switched on, or a cookie recording that you asked to opt out of ad sharing. These cannot be turned off without breaking the thing they support, and they carry no advertising identifiers.</p>

<h3>2. Analytics</h3>
<p>If we use Google Analytics, it sets cookies that count visits and record which pages were viewed and in what order. We use this to find pages people leave quickly and fix them. You can opt out with the <a href="https://tools.google.com/dlpage/gaoptout">Google Analytics opt-out browser add-on</a>.</p>

<h3>3. Advertising</h3>
<p>If we run Google Ads, conversion tracking tells us which advertisement led to an order, and remarketing can show our advertisements to people who visited this site. Both rely on cookies or similar identifiers. Turn off personalized advertising at <a href="https://adssettings.google.com">adssettings.google.com</a>, or opt out of sharing entirely on our <a href="your-privacy-choices.php">Your Privacy Choices</a> page.</p>

<h2>Controlling cookies in your browser</h2>
<p>Every major browser lets you block or delete cookies, usually under Settings, then Privacy. Blocking all cookies is your right and will not stop you reading this catalog or ordering by telephone; it may interfere with a hosted payment page later on.</p>
<p>Browsers also offer a Global Privacy Control setting or extension. We honor that signal &mdash; see <a href="your-privacy-choices.php">Your Privacy Choices</a>.</p>

<h2>Do Not Track</h2>
<p>Browsers may send a Do Not Track header. There is still no agreed industry standard for responding to it, so we do not rely on it. We do honor Global Privacy Control, which is the signal with legal effect in California and several other states.</p>

