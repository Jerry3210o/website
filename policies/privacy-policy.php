    <h1>Privacy Policy</h1>
    <p><strong>Effective date:</strong> September 22, 2026</p>
    
<h2>Who we are</h2>
<p>Porchlight General LLC, trading as Porchlight General, 118 Depot Street, Suite 4, Springfield, IL 62701. We are the business responsible for the personal information described here.</p>

<h2>What we collect</h2>
<ul>
  <li><strong>Identifiers and contact details:</strong> your name, delivery address, email address, and telephone number, when you place an order or contact us.</li>
  <li><strong>Order information:</strong> the items you bought, the amount, and the delivery details.</li>
  <li><strong>Payment information:</strong> handled entirely by our payment provider. We never receive or store your full card number.</li>
  <li><strong>Technical information:</strong> your IP address, browser type, and the pages you visited, recorded in ordinary web server logs and by our analytics provider.</li>
</ul>
<p>We do not collect Social Security numbers, financial account numbers, precise geolocation, biometric data, or any of the categories that California law defines as sensitive personal information.</p>

<h2>Where it comes from</h2>
<p>Directly from you, when you order, call, or write to us; automatically from your browser when you visit the site; and from our shipping carriers, when they tell us a parcel was delivered.</p>

<h2>Why we use it</h2>
<ul>
  <li>To take, pack, and deliver your order, and to contact you about it.</li>
  <li>To handle returns, refunds, and warranty claims.</li>
  <li>To keep the records that tax and consumer-protection law require.</li>
  <li>To understand which pages of this site people use, so we can improve it.</li>
  <li>To advertise our own products, as described below.</li>
</ul>

<h2>Checkout details are not saved</h2>
<p>While online payment is not available, the details you type into our checkout page are not stored by us, not emailed, and not used for any purpose. The result page has no code that reads them.</p>

<h2>Who we share it with</h2>
<ul>
  <li><strong>Shipping carriers</strong> &mdash; your name and address, so that they can deliver the parcel.</li>
  <li><strong>Our payment provider</strong> &mdash; when online payment is switched on, they process your card details on their own page under their own privacy policy.</li>
  <li><strong>Our hosting provider</strong> &mdash; which stores this website and its server logs.</li>
  <li><strong>Google</strong> &mdash; for website analytics and advertising, as described below.</li>
  <li><strong>Law enforcement or regulators</strong> &mdash; only when we are legally required to.</li>
</ul>
<p>We do not sell your personal information for money. We have never done so.</p>

<h2>Cookies, analytics, and Google advertising</h2>
<p>This site sets no cookies of its own. If we use Google Analytics, Google Ads conversion tracking, or Google Ads remarketing, those services set cookies or similar identifiers in your browser and may use them to show you our advertisements on other websites.</p>
<p>You can opt out of personalized Google advertising at <a href="https://adssettings.google.com">adssettings.google.com</a>, and you can install the Google Analytics opt-out browser add-on from <a href="https://tools.google.com/dlpage/gaoptout">tools.google.com/dlpage/gaoptout</a>. Our <a href="cookie-policy.php">Cookie Policy</a> explains the categories and your browser-level controls.</p>
<p>Under California law, using advertising cookies that share identifiers with an advertising network can count as &ldquo;sharing&rdquo; personal information for cross-context behavioral advertising. You can opt out of that at any time &mdash; see <a href="your-privacy-choices.php">Your Privacy Choices</a>.</p>

<h2>California rights (CCPA/CPRA)</h2>
<p>If you live in California you have the right to:</p>
<ul>
  <li><strong>Know</strong> what personal information we have collected about you, where it came from, why, and who we shared it with.</li>
  <li><strong>Delete</strong> the personal information we hold about you, subject to the records we must keep by law.</li>
  <li><strong>Correct</strong> inaccurate personal information.</li>
  <li><strong>Opt out</strong> of the sale or sharing of your personal information.</li>
  <li><strong>Limit</strong> the use of sensitive personal information &mdash; though we do not collect any.</li>
  <li><strong>Non-discrimination</strong>: we will never charge you a different price or give you worse service for exercising any of these rights.</li>
</ul>
<p>To exercise any of them, call <a href="tel:+15555550147">(555) 010-0147</a> or email <a href="mailto:orders@porchlightgeneral.example">orders@porchlightgeneral.example</a>. We respond within 45 days, and will tell you if we need the extra 45 days the law allows. We may ask you to confirm details of a past order so we can be sure it is you.</p>

<h2>Global Privacy Control</h2>
<p>We honor the Global Privacy Control (GPC) signal. If your browser or extension sends a GPC signal, we treat it as a valid request to opt out of the sale or sharing of your personal information, and we apply it to that browser without asking you for anything else.</p>

<h2>Other state privacy rights</h2>
<p>Residents of Virginia, Colorado, Connecticut, Utah, Texas, Oregon, and other states with comprehensive privacy laws have comparable rights to access, correct, delete, and obtain a copy of their personal information, and to opt out of targeted advertising. Use the same telephone number or email address above; we apply the same process to everyone regardless of where they live. Where state law provides an appeal from our decision, you may appeal by writing to the same address, and we will respond within the time your state allows.</p>

<h2>Children</h2>
<p>This site is not directed to children under 13, and we do not knowingly collect personal information from them. If you believe a child has given us information, call us and we will delete it.</p>

<h2>How long we keep it</h2>
<p>Order records are kept for seven years, which is what tax and business record-keeping requires. Customer service emails are kept for three years. Web server logs are kept for 90 days. When a period ends, the records are deleted.</p>

<h2>Security</h2>
<p>This site is served over an encrypted connection. Access to order records is limited to the people who need it to do their jobs. No system is perfectly secure, and we will not pretend otherwise; if a breach ever affects your information, we will notify you as state law requires.</p>

<h2>Changes</h2>
<p>If we change this policy we will update the effective date at the top and post the new version here. Material changes will also be announced on our home page for 30 days.</p>

