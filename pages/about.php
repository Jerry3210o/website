  <h1>About Porchlight General</h1>
  <div class="two-col">
    <div>
      <p>Porchlight General is a mail-order and online catalog of well-made household goods: kitchen classics, pantry and canning supplies, things for the home and hearth, and radios, clocks and keepsakes.</p>
      <p>We built this catalog for shoppers who would rather read a description than watch a video, who want the item number printed where they can find it, and who sometimes prefer to pick up a telephone and talk to somebody. That is the whole idea, and everything on this site follows from it.</p>
      <h2>How we choose what we sell</h2>
      <p>Three questions decide whether something goes in the catalog. Does it do a real job? Will it still be working in ten years? Can we describe it honestly, in plain words, without leaning on adjectives? If an item fails any of the three, it does not go in.</p>
      <p>That rules out a great deal. It rules out anything that needs an app, anything with a screen where a dial would do, anything built to be replaced in two seasons. What it leaves is mostly cast iron, glass, wood, cotton, and steel &mdash; the materials that were used for these jobs before there were alternatives, and are still the right answer.</p>
    </div>
    <div>
      <p><img src="../assets/images/brand/about.jpg" alt="A general store interior with shelves of kitchen goods and a wooden display table" width="696" height="900"></p>
    </div>
  </div>

  <section class="section">
    <h2>How we describe things</h2>
    <p>Every description on this site was written for that exact item, by a person who read its specifications. Dimensions are in inches, weights in pounds. If a product needs care, we tell you what the care is. If it has a limitation &mdash; a bread box that will not stop bread going mouldy in a humid kitchen, a wool throw that must not go in a dryer &mdash; we say so on the page rather than letting you find out.</p>
    <p>We do not show star ratings or customer quotes, because this store is new and we have no verified customers yet. When we do, their reviews will appear on the product pages and they will be real ones. We do not show crossed-out &ldquo;was&rdquo; prices either, because we have no price history to compare against and inventing one would be a lie.</p>
  </section>

  <section class="section">
    <h2>Who to talk to</h2>
    <p>Our telephone number is at the top of every page for a reason: for many of the people this catalog is for, a telephone is simply the better way to sort something out. Call <a href="tel:+15555550147">(555) 010-0147</a> during Mon&ndash;Fri 9 AM&ndash;6 PM ET and a person will answer. You can order that way, ask about a product before you buy, start a return, or check where a parcel is.</p>
    <p>If you would rather write, email <a href="mailto:orders@porchlightgeneral.example">orders@porchlightgeneral.example</a> or send a letter to Porchlight General LLC, 118 Depot Street, Suite 4, Springfield, IL 62701. Our owner, Ellen Marsh, reads the letters.</p>
  </section>

  <section class="section">
    <h2>How this website is built</h2>
    <p>Deliberately plainly. Text is set at nineteen pixels or larger everywhere, including the legal pages. Links are underlined. Buttons are big and say what they do. Nothing on this site moves on its own, pops up over what you are reading, or starts playing sound. There are no countdown timers and no &ldquo;three people are looking at this&rdquo; messages, because those exist to rush you, and rushing people is how they get talked into things.</p>
