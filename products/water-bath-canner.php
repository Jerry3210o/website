    <h2>About this item</h2>
    <p>Water-bath canning is simple — jars of high-acid food, boiling water, a set number of minutes — but it only works if the pot is deep enough. The rule is two inches of water over the tops of the jars plus room to boil, and an ordinary stockpot rarely has it. This twelve-quart canner does, and it comes with the rack that makes the job safe.</p><p>The rack is the part people forget. It holds jars up off the direct heat of the pot bottom so they do not crack or scorch, keeps them from knocking into each other during a rolling boil, and lifts all seven out together when the time is up. With the rack hooked on the rim, jars drain for a second before you move them — no fishing in boiling water with tongs.</p><p>This is honest equipment: a big aluminum pot, a fitted lid, and a wire rack. Tomatoes, applesauce, pickles, jam, and anything else with enough acid go in it. Low-acid vegetables and meat need a pressure canner instead — no water-bath pot of any size can do that job, and no recipe should tell you otherwise. The rest of the year, it is the pot for corn on the cob, a crab boil, or a double batch of chili.</p>
  </section>

