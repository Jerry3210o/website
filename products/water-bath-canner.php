  <section class="signature">
    <h2>How it&rsquo;s used</h2>
    <p>Fill the canner about half full, bring it to a simmer while you fill jars, then lower the loaded rack in and add boiling water until the jars are covered by two inches. Start timing when the water returns to a full rolling boil, not before.</p><p>When the time is up, turn off the heat, wait five minutes, then lift the rack and set jars on a towel an inch apart to cool overnight. Do not tighten bands while they cool, and do not press the lids until morning.</p>
  </section>

  <section class="notice notice-error"><h2>Safety note</h2><p>A loaded canner is heavy and full of boiling water. Set it on a back burner, keep the handles turned in, and never lift the whole pot while it is full — lift the rack instead. Follow a tested recipe for every processing time.</p></section>

