    <p>Bread belongs in a basket. A plate lets rolls slide, a bowl hides them, and a plastic container sweats — but a basket lined with a folded napkin holds the loaf, keeps it warm, and looks right in the middle of the table without anyone having to arrange anything. This one is hand-woven wicker over a light wooden frame, fourteen inches long, which is the size that takes a sliced loaf, a dozen dinner rolls, or a stack of cornbread wedges.</p><p>Out of season it does what every good basket does, which is whatever you need. Apples and pears keep better in it than in a bowl because air reaches them from underneath. Onions and potatoes last longer in the open weave than in a bag. On a hall table it takes the mail and the keys; on a porch it carries the tomatoes in from the garden.</p><p>Wicker is strong, light, and forgiving. Shake the crumbs out, wipe it with a barely damp cloth, and let it dry fully before it goes back on the shelf. Do not soak it and do not leave it in the sun for a season, and the weave will stay tight for many years. It weighs about two pounds, so it is easy to pass down a table even when it is full.</p>
