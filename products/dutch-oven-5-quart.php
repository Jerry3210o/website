    <p>A Dutch oven is the pot you reach for when dinner needs time: pot roast on a Sunday, bean soup on a cold week, chicken and dumplings that has to feed six. This one holds five quarts and is cast from iron in a single heavy piece, with a close-fitting lid and loop handles on both sides that take oven mitts easily.</p><p>The thick iron walls are the whole point. Heat comes at the food gently from every side instead of blasting up through a thin base, which is why a stew from a pot like this tastes different from one made in a light stockpot — the onions melt instead of scorching and the liquid never catches on the bottom. The heavy lid returns moisture to the pot, so a roast stays juicy through three hours in a low oven.</p><p>Bread is the other reason people buy it. The no-knead loaf recipe printed on the back of half the flour bags in America is written for exactly this pot: the lid traps steam for the first half of the bake and gives you a bakery crust in a home oven. Season it like any bare cast iron — wash, dry on the burner, wipe with oil — and it will be cooking dinners long after the rest of the cookware has been replaced.</p>
