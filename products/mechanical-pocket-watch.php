    <p>A pocket watch is a different way of carrying the time. You reach for it, open the lid, read it, and close it — a small deliberate act instead of a glance at a lit rectangle. This one is a true mechanical: you wind the crown a dozen turns in the morning and it runs through the day on that alone. There is no battery to replace and nothing to charge, ever.</p><p>The case is a polished gold tone, an inch and three quarters across, with a hinged lid that snaps closed over the crystal so keys and coins cannot scratch it in a pocket. The dial is white with black Roman numerals and a small seconds hand at the bottom, which is both the traditional layout and the readable one. Hold it at arm&#x27;s length and the numerals are still clear.</p><p>The chain is fourteen inches with a spring-ring clip at the end — long enough to run from a belt loop to a front pocket or across a vest in the old way, and strong enough that the watch will not be dropped. It is a gift people remember receiving, and just as often it is bought for the pleasure of owning a working mechanical thing in a house full of batteries. A mechanical watch keeps time to within a minute or two a day, which is the honest tradeoff for never needing a battery.</p>
