    <p>Wind it at the same time every day — most people do it with the morning coffee — about a dozen turns of the crown until it gently stops. Do not force it past that point; the mainspring is fully wound when it resists.</p><p>Set the time by pulling the crown out one click and turning it forward. Keep the watch out of water and away from speakers and magnets, which are the two things that upset a mechanical movement.</p>
