  <section class="signature">
    <h2>How it&rsquo;s used</h2>
    <p>Start it on medium heat, not high — cast iron holds heat, so it needs less flame than you think. Give it three or four minutes to warm through before food goes in, and it will brown evenly from edge to edge.</p><p>Care is simple and takes one minute: wash by hand with warm water (a little soap is fine), dry it on a low burner until the water is gone, then wipe the inside with a few drops of cooking oil on a paper towel. Stored dry, it will not rust. If rust ever appears, scrub it off, oil the pan, and carry on — cast iron forgives everything except being left wet.</p>
  </section>

