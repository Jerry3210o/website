  <section class="signature">
    <h2>How it&rsquo;s used</h2>
    <p>Fill it to no more than an inch below the spout so the whistle sounds properly, and lift the spout cover before pouring. Never fill it past the spout — boiling water needs the airspace.</p><p>Twice a year, boil a cup of white vinegar with three cups of water in it, let it stand an hour, and rinse. That clears the mineral scale that makes a kettle slow and a whistle weak.</p>
  </section>

  <section class="notice notice-error"><h2>Safety note</h2><p>Steam from the spout will scald. Lift the spout cover with the handle, not your fingers, point the spout away from you, and never open the lid while the kettle is on the heat.</p></section>

