    <h2>About this item</h2>
    <p>A whistling kettle is a safety device as much as a convenience. Water left boiling on a burner boils dry and scorches the pan, or worse; a kettle that whistles makes that nearly impossible, because the whistle carries into the next room and keeps going until somebody comes. For anyone who has ever walked away from the stove and forgotten why they went in there, it is the single most useful thing in the kitchen.</p><p>This one is polished stainless steel with a capacity of two quarts — eight cups, enough for a pot of tea and a hot water bottle, or for four mugs with some left over. The base is wide, which boils water faster and keeps the kettle steady on a burner or grate, and it works on every stove including induction. The spout cover lifts with a thumb and the handle is fixed in the upright position, so it never flops down onto the hot body.</p><p>Stainless is what makes it last. It will not chip like enamel or corrode like aluminum, it does not hold flavors, and a scale-cleaning with vinegar twice a year keeps the inside bright even in hard-water country. Nothing about it is electronic, so there is nothing to fail: it is a metal pot with a whistle, and that is the whole of its design.</p>
  </section>

