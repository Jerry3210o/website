    <h2>About this item</h2>
    <p>Small print is everywhere it should not be: the dosage on a bottle, the serial number on the back of an appliance, the date on a warranty card, the fine line on an insurance letter. A good magnifier makes all of it readable again, and a good one means a real glass lens, a size you can actually use, and a handle that keeps your hand steady.</p><p>The lens here is three inches across — wide enough to show a full line of text at once, which is what separates a useful magnifier from the keychain kind that shows you four letters at a time. It is ground glass, not molded plastic, so the image stays sharp to the edge and does not scratch into a haze in a year in a drawer. Three times magnification is the range that works for reading; stronger lenses sound better but have to be held so close to the page that they become awkward.</p><p>The handle is turned and shaped to fill a hand, which matters more than it sounds: a thin handle has to be gripped, where a thick one just rests in the fingers, and that is the difference between reading a paragraph comfortably and giving up on it. There is nothing electrical here — no battery to die, no light to burn out, nothing to switch on. Keep one by the telephone and one in the kitchen drawer.</p>
  </section>

