    <p>Cribbage is the card game that has kept more people company than any other — at kitchen tables, in cabins, aboard ships, and through long winters — and it needs a board. This one is a straight twelve-inch wooden board with two tracks of a hundred and twenty holes, which is all the game requires and nothing it does not.</p><p>The details that matter on a cribbage board are the hole size and the pegs. These holes are drilled large enough to find by feel as well as by sight, which anyone with less-than-perfect close vision will appreciate around the third hand of the evening. The pegs are turned metal rather than thin plastic, so they do not bend, snap, or vanish into a rug — and the board has a compartment underneath with a sliding cover where all six live between games.</p><p>Six pegs means four in play and two spares, because the one thing every old cribbage board is missing is a peg. The wood is finished smooth and the tracks are marked at the corners so nobody loses their place. Pair it with a deck of cards and you have the entire equipment list for a game that two people can play for fifty years without getting tired of it.</p>
