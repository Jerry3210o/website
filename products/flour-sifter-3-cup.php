    <h2>About this item</h2>
    <p>Recipes from the cookbooks most of us learned on — the church cookbooks, the flour-bag classics — assume sifted flour, and there is no real substitute for the tool. This three-cup sifter is the classic squeeze-handle pattern: fill it, hold it over the bowl, work the trigger a few times, and the flour falls in a light, even snowfall with every lump broken.</p><p>Sifting matters more than it gets credit for. Flour packs down in the bag, so a cup scooped straight from it can weigh a quarter more than the recipe intends — the difference between a tender cake and a heavy one. Sifted flour also takes liquid evenly, which is why biscuit and cake batters come together with less stirring, and less stirring means a lighter crumb.</p><p>The body is stainless steel with a fine mesh screen and a rolled top edge for leveling. Three cups is the size that matches a standard layer cake or a double batch of biscuits, and it is small enough to live in the flour drawer. Use it for cocoa when a recipe says sift together, and for dusting powdered sugar over a finished cake, where it gives the even professional finish a spoon never will.</p>
  </section>

