    <p>For camp-style coffee, add coarse grounds straight to the water — a tablespoon per cup — bring it just to a boil, pull it off the heat, and let it stand three minutes so the grounds settle. A splash of cold water settles them faster. Pour slowly and the grounds stay behind in the pot.</p><p>Dry it upside down after washing. If you chip the enamel down to bare steel, dry that spot carefully after each wash and the pot will give you years more service.</p>
