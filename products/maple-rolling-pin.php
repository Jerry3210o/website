    <h2>About this item</h2>
    <p>A good rolling pin is a lifetime tool, and the American standard has always been hard maple: heavy enough to do the work, fine-grained enough to roll smooth, durable enough to hand down. This one is turned from solid maple with a ten-inch barrel and handles that spin freely on steel rods — the pattern most bakers grew up with.</p><p>Weight is what separates a real pin from a decorative one. At two pounds, this pin flattens chilled pie dough with its own mass. You guide it rather than press it, which keeps the dough from being overworked and keeps your wrists out of it. The maple surface, rubbed with a little flour, releases even rich butter doughs cleanly, and unlike marble or steel it never sweats or chills your hands.</p><p>Maple earns its keep beyond pastry: crushing graham crumbs in a bag, pressing pizza dough, flattening chicken cutlets between sheets of wax paper. Care is the same as a wooden spoon — wipe it clean, never soak it, give it an occasional rub of mineral oil. Do that and there is no reason this pin will not be rolling out Thanksgiving pies thirty years from now.</p>
  </section>

