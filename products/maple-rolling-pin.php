  <section class="signature">
    <h2>How it&rsquo;s used</h2>
    <p>Flour the pin, not just the board, and roll from the center of the dough outward, giving the dough a quarter turn between passes. The turning — not the pressure — is what keeps a crust round and even. If dough sticks, a bench scraper and another dusting of flour fix it faster than force.</p><p>Wipe the barrel with a damp cloth after use and stand it to dry. Once a month rub in a teaspoon of food-safe mineral oil overnight; the wood stays smooth and never dries out.</p>
