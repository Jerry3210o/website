    <h2>About this item</h2>
    <p>A doorstop has one job and this one does it by being heavy. Five pounds of cast iron in a stepped base holds an interior door open against the draft from an open window, the pull of a hallway, or the swing of a house settling — which the light rubber wedges cannot do, and which matters if you are carrying laundry through with both hands full.</p><p>The figure is the classic standing soldier that cast-iron doorstops have taken since the nineteenth century, cast in one piece and painted dark. The base is stepped and flat, wide enough that a door leaning on it pushes it along the floor rather than tipping it over, and the whole thing is solid metal with nothing inside to rattle or come loose.</p><p>It suits an old house and an ordinary one equally. On carpet it stays put; on wood or tile, a felt pad on the base — not included, but sold anywhere — keeps it from marking the floor. It also serves as a serious bookend at the end of a shelf, where five pounds holds up a row of hardbacks that lighter bookends let slump. The paint is durable but not indestructible, and chips on a cast-iron doorstop are, historically speaking, part of the look.</p>
  </section>

