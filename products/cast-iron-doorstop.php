    <h2>How it&rsquo;s used</h2>
    <p>Set it against the door edge, not flat against the face, and the weight does the work. On a door that swings shut hard, put it at the far corner where the leverage is greatest.</p><p>Keep it dry. Cast iron under paint will rust at a chip if it sits in a damp doorway; a dab of paint over a chip settles the matter for another decade.</p>
  </section>

