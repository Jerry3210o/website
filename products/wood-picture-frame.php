    <h2>About this item</h2>
    <p>The photographs worth framing are usually the plain ones: a wedding portrait, a grandchild&#x27;s school picture, the last good picture of somebody. A frame for those should not compete with them, which is why this one is what it is — a plain dark hardwood molding about an inch wide, a cream mat, and clear glass.</p><p>The mat is what makes a framed photograph look finished. It sets the picture in from the wood by an inch or so, gives the eye somewhere to rest, and keeps the print from touching the glass, which is what causes photographs to stick and spoil over the years. Take the mat out and the frame holds a 9 by 11 print instead, so it works either way.</p><p>It opens from the back with metal turn tabs, so changing a photograph takes a minute and no tools. The backing has both a hanging notch and a folding easel leg, which means the same frame works on a wall, a mantel, a hall table, or a desk — you decide after it arrives rather than before you order. Buy three or four; a wall of the same plain frame in different sizes looks deliberate in a way that a wall of mismatched ones never does.</p>
