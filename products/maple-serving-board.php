    <p>A board with a handle is a serving board and a cutting board at once, which is why this shape has been in American kitchens since long before either term existed. Slice the bread on it, set the cheese and apples beside the slices, pick it up by the handle, and the board becomes the platter. Nothing gets transferred, nothing extra gets washed.</p><p>It is cut from solid maple — closed-grain, hard, and pale, the same wood used for butcher blocks. Maple is gentle on knives, which matters more than most people realize: glass and stone boards dull a good knife in a season, where wood lets the edge sink slightly and come back. The surface is sanded smooth and finished with food-safe oil only, with no varnish to chip into the food.</p><p>At eighteen inches including the handle and eleven inches wide, it is big enough for a loaf of bread or a roast chicken and still small enough to fit a dish rack and a cupboard shelf. Wash it by hand, dry it standing up, and give it an oil rub when the color starts to look thirsty. Boards like this end up darkening and picking up knife marks over the years, which is exactly what a working board should do.</p>
