    <p>Fill the pot with cold water to the cup line, set the tube and basket in place, and spoon in coarse-ground coffee — about one rounded tablespoon per cup to start. Bring it up over medium heat until it perks steadily, then turn the heat low and let it go six to eight minutes. Pour the first cup and adjust grounds or minutes tomorrow.</p><p>Rinse the basket and tube after every use so coffee oils do not build up, and wash the pot with baking soda and water once a month to keep the inside bright.</p>
