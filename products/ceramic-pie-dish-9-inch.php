    <p>Ask anyone who bakes and the pie dish that matters is the plain nine-inch one. This is that dish, in glazed stoneware with a fluted rim: nine inches across the top, an inch and a half deep, wide enough in the rim to crimp a crust properly and pretty enough to carry to the table without transferring anything.</p><p>Stoneware bakes differently from thin metal, and for pie it bakes better. It warms gradually and holds heat steadily, so the bottom crust sets and browns instead of burning where a light pan runs hot. That gentle heat is exactly right for custard pies — pumpkin, pecan, chess — that curdle in fast pans, and it suits the long slow bake a deep apple pie wants in the fall.</p><p>The glaze is smooth and non-porous, so fruit acids do not stain it and yesterday&#x27;s savory quiche leaves nothing behind for today&#x27;s berry pie. It is safe in the oven, the refrigerator, the freezer, the microwave, and the dishwasher, and it handles scalloped potatoes, a small crumble, or a pan of baked eggs just as well as it handles pastry. Most kitchens end up wanting two.</p>
