    <p>Every well-used chair in the country has a throw over the back of it, and this is a good one: fifty by sixty inches, which covers a seated adult from shoulder to ankle without pooling on the floor, in a wool blend that holds heat the way wool does while staying light enough to nap under.</p><p>The pattern is woven, not printed — bands of rust, olive, cream and brown across the width, with twisted fringe at both ends. Woven color does not fade the way printing does after a year of Saturday afternoons and washing. The blend keeps the warmth and the springiness of wool while taking the edge off the prickle some people find in pure wool, and it stays warm even when the room is not.</p><p>A throw earns its place by being where you sit. Keep it folded over the back of the chair, the arm of the sofa, or the foot of the bed, and it does its job on the cold evenings between when the sun goes down and when the heat comes on — which, for most households watching the thermostat, is a real saving. Wash it cold on a gentle cycle and lay it flat to dry; wool blends should not see a hot dryer.</p>
