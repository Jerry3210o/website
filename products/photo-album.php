    <p>Photographs on a phone are photographs nobody looks at. An album on a shelf gets opened — by grandchildren, at Thanksgiving, by whoever is in the room when somebody says do you remember. This is a proper one: eleven by twelve inches, cloth-bound in a red and brown plaid, with a strap and snap that holds it closed on the shelf.</p><p>Inside are fifty heavy black pages, post-bound so the album lies flat when it is open and so extra pages can be added later without rebinding. Black pages are the traditional choice for good reason: prints of any era look right against them, and white pencil or a silver pen writes legibly in the margin. Mount prints with photo corners rather than adhesive, and they can come out again undamaged in fifty years.</p><p>The space beside each photograph is the part that matters most. Write the names, the place, and the year, even when it seems obvious — especially when it seems obvious, since the obvious is exactly what gets forgotten first. Customers tell us they buy one album and end up writing captions for two hundred loose prints that have been in a shoebox for thirty years, which is, we think, the best possible use of twenty-eight dollars.</p>
