    <h2>About this item</h2>
    <p>A clock on the mantel is the one everyone in the house looks at, which is why the dial matters more than anything else about it. This one has a six-inch white face with black Roman numerals and long black hands — the combination that stays readable from a chair on the other side of the room, and stays readable in the low light of a winter afternoon.</p><p>The case is solid wood with a warm brown finish, a gently arched top, and a glass lens over the dial that keeps dust off the hands. It is eleven inches wide and nine tall, which sits comfortably on a mantel, a bookshelf, a hall table, or a bedroom dresser without crowding what is around it. The weight — about five pounds — keeps it where you put it.</p><p>Inside is a quartz movement that runs on a single AA battery for roughly a year. There is nothing to wind, nothing to plug in, and nothing that has to be reset after a power cut, which is the practical advantage over both an antique clock and a digital one. The movement sweeps rather than ticking sharply, so it will not keep a light sleeper awake in a bedroom. Setting it is a single knob on the back.</p>
