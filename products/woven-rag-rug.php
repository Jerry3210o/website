    <p>The rag rug is the most practical floor covering ever devised: strips of cotton woven tight on a loom, flat enough to lie still, tough enough for a doorway, and cheap enough to wash every week without thinking about it. This one is twenty-four by thirty-six inches — the size for in front of a kitchen sink, inside a back door, or beside a bed where your feet land in the morning.</p><p>Because it is woven rather than tufted, there is no pile to crush and no backing to crumble after two years. The whole rug is about a quarter-inch thick, which matters more than it sounds: a thin rug does not catch a toe or a walker wheel, and it slides under a door that clears the floor by very little. Both sides are the same, so when one has taken its share of wear you flip it and start again.</p><p>Colors are mixed the way rag rugs always were, since they came from what was on hand. That variation is what lets a rug like this sit in any room without matching anything. Wash it cold with like colors, tumble dry low, and it comes out flat and ready. Most households end up with three or four of them, which is exactly how it has always gone.</p>
