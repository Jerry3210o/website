    <p>Coir — the stiff fiber from a coconut husk — has been the doormat material of choice for a century and a half because nothing else scrapes as well. The bristles are hard enough to take grit out of a boot tread, open enough to let the dirt fall through instead of holding it at the surface, and tough enough to sit outside through a full year of weather.</p><p>This mat is thirty by eighteen inches, which is wide enough that both feet land on it at once — the reason bigger mats work better than small ones, since people rarely wipe twice. WELCOME is stamped across it in red, in the plain block lettering these mats have always used. The backing is a firm layer that keeps the mat flat and stops it curling at the corners, which is where a cheap mat becomes a trip hazard.</p><p>Care is shaking it out over the porch rail, and that is genuinely all. Do not hose it down and leave it to sit wet, because coir is a natural fiber and rot starts underneath. Keep it under an overhang if you can, turn it end for end every few months so the wear evens out, and it will hold up for years. When it finally wears thin, it goes in the garden as mulch, which is more than most household goods can say.</p>
