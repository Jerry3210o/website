    <h2>How it&rsquo;s used</h2>
    <p>Set it on a solid surface, not a wobbly side table — a turntable that rocks makes the needle skip. Check the speed before you lower the arm; a 45 played at 33 is the most common complaint we hear, and it is not the machine.</p><p>Replace the stylus about once a year if you play records regularly. A worn stylus is what scratches records, and a new one costs a few dollars.</p>
