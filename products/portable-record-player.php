    <h2>About this item</h2>
    <p>Most record players sold today assume you already own an amplifier and a pair of speakers. This one does not. It is the self-contained portable that a lot of people learned to play records on: open the lid, set the speed, put the record on, lower the arm, and sound comes out of the machine itself.</p><p>Three speeds is the part that matters for anyone with a real collection. Thirty-three for LPs, forty-five for singles with the adapter, and seventy-eight for the shellac records in the closet that nothing made in the last forty years will play. The tone arm has a counterweight and a replaceable stylus, and the speed selector is a simple switch rather than a menu.</p><p>The case closes with the platter and arm inside and carries by a handle, which is what makes it portable in the honest sense: it goes to the porch, to a daughter&#x27;s house, to a church hall. It plugs into a wall outlet with a five-foot cord and needs nothing else. If you later want it through a stereo, the output jack on the back will do that — but out of the box it works on its own, which is the whole point of a machine like this.</p>
  </section>

