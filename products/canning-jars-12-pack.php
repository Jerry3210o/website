  <section class="signature">
    <h2>How it&rsquo;s used</h2>
    <p>Wash the jars in hot soapy water and keep them warm until you fill them — a cold jar going into hot water can crack. Leave the headspace your recipe calls for, wipe the rim clean, and finger-tighten the band only; the air has to escape for the seal to form.</p><p>After the jars cool, press the center of each lid. A sealed lid does not flex. Store sealed jars with the bands off so you can see at a glance if a seal ever fails, and use a fresh flat lid every time you can.</p>
  </section>

  <section class="notice notice-error"><h2>Safety note</h2><p>Never can in a jar with a chipped rim — it will not seal. Follow a tested recipe for processing times; under-processed low-acid food is not safe to store at room temperature.</p></section>

