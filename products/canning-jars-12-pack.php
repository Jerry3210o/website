    <p>The mason jar is the most useful container ever made, and a dozen quarts is the size most households start with. These are wide-mouth jars: the opening is the full diameter of the jar, so a canning funnel drops straight in, a ladle fits without dripping down the side, and whole peach halves or pickle spears go in without being forced. They take two-piece lids — a flat sealing disc and a screw band — which is the system every tested canning recipe in America is written around.</p><p>Glass is the reason canning works. It does not react with vinegar or tomatoes, it does not hold last year&#x27;s flavors, and it shows you exactly what is inside and whether the seal is still holding. These jars are annealed for heat, so they take a boiling water bath and, with the right equipment, a pressure canner. Between seasons they turn into refrigerator storage, dry goods canisters, soup for the freezer (leave headspace), or the everyday drinking glasses that half the country already uses them as.</p><p>Screw bands are reusable for years. Flat lids are single-use for canning — that is not a sales tactic, it is how the sealing compound works — and replacements are sold everywhere. Buy the dozen, and you will find uses for all twelve before the first tomatoes are ready.</p>
