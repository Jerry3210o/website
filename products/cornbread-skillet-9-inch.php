    <p>Cornbread is a cast-iron food, and this is a pan made for it: nine inches across, shallower than a frying skillet, with straight-ish sides that give the bread a browned edge all the way around. Heat the greased pan first, pour in the batter so it sizzles on contact, and that sizzle becomes the crisp bottom crust that cornbread baked in a cold glass dish never gets.</p><p>The iron does the rest. It carries steady heat up every wall of the pan, so the bread rises evenly and browns rather than steams, and it comes out of the oven still hot enough to melt butter ten minutes later at the table. A wedge cut from a pan like this — crisp on the bottom, tender through the middle — is the version most people are remembering when they say cornbread.</p><p>It earns its space beyond cornbread. Peach cobbler, a pan of biscuits, a skillet brownie with edges for everybody, corn sticks for a pot of chili: anything you want more crust on belongs here. The pan arrives pre-seasoned, and care is the same one-minute routine as any cast iron — hand wash, dry on a warm burner, wipe with oil. Like all plain cast iron, it will outlive its receipt by a generation.</p>
