    <h2>About this item</h2>
    <p>A porch rocker is a piece of furniture people use for decades, so the things to get right are the seat, the back, and the runners. This one has a generous twenty-five-inch seat contoured to the shape of a person rather than flat, a tall slat back that supports you to the shoulders instead of stopping at the middle of the spine, and arms at a height that gives you something to push up from when you stand — which is the detail that decides whether a chair suits an older body.</p><p>The frame is hardwood, joined and screwed rather than stapled, and finished in a painted, sealed coat that stands up to damp air and sunlight on a covered porch. The runners are wide and long, giving an easy, unhurried rock without the tipping feel that short-runner chairs have, and they sit flat on porch boards, brick, or a deck.</p><p>It arrives mostly assembled: the back and the runners attach with the included hardware and a screwdriver, which takes about twenty minutes. Keep it on a covered porch rather than out in the weather, and give the paint a fresh coat every few years, and this is a chair that will still be rocking when it belongs to somebody else in the family. A cushion is shown in the photograph and is not included.</p>
