    <p>Cheesecloth is one of those plain cotton things that has no substitute when you need it. This is nine square feet of unbleached grade-50 weave — open enough to let liquid through quickly, tight enough to hold back the bits you are straining out. Nothing is added to it: no bleach, no sizing, no finish that could end up in the food.</p><p>The jobs it does are the ones paper towels tear on and fine strainers clog with. Line a colander with two layers and pour in a pot of stock, and you get a clear broth with no skimming. Hang a knot of it over a bowl and yogurt turns thick overnight. Wring it around grated potatoes and the latkes fry crisp instead of steaming. Tie rosemary, thyme, peppercorns, and a bay leaf into a square and drop it in the stew, then lift the whole bundle out before serving.</p><p>It also belongs in the canning kitchen for straining jelly — a jelly bag made from four layers gives you clear jelly without pressing, which is what keeps it from going cloudy. Rinse it out right away, wash it in hot water, and most pieces give you several uses before the weave goes soft. Because it is a fabric that touches food directly, this item is not returnable once the package is opened.</p>
